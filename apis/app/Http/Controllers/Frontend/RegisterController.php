    /**
     * 註冊帳號
     *
     * @noinspection D
     */
    public function __invoke(RegisterRequest $request)
    {
        $input = $request->validated();

        // 風控IP限制(4096)：來源IP有勾選「註冊」的啟用規則 → 擋註冊並累計重複次數
        $this->guardIpRestriction();

        $userData = $this->getUserContext();
        $domainAgent = $userData->agent;

        // 關閉模式只能走 v2：v1 收手填帳號，會繞過自動產生帳號與一號一帳。
        // 關閉模式的組別一定有註冊欄位設定，前台會走 v2，正常操作走不到這裡
        if ($this->memberFieldSettingService->isUsernameAutoGenerated($domainAgent)) {
            throw new ApiException(__('error_message.9999'), 9999);
        }

        $inviteCode = $input['invitation_code'] ?? '';
        $inviteCodeType = $input['invitation_code_type'] ?? 0; // 由 api/agent/template 取得

        if (empty($inviteCode)) {
            // 推薦碼必填:依 3970 config 的註冊欄位 referral_code 是否必填
            if ($this->memberFieldSettingService->isReferralCodeRequired($domainAgent)) {
                throw new ApiException(__('error_message.registration not allow code empty'));
            }
            $inviteCode = $domainAgent->code;
        }

        [$agent, $sponsor, $eventSummary, $memberType] = $this->registerService->detectAgentAndSponsor($inviteCode, $inviteCodeType, $domainAgent);

        // 檢查 username & nickname 是否包含禁用字
        $this->registerService->validateBannedWords($input, $agent);

        $countryId = 0;
        if (isset($input['country_code'])) {
            $countryId = $this->registerService->getCountryIdByCode($input['country_code']);
        }

        try {
            DB::beginTransaction();
            // 是否通過手機驗證
            $mobileValidate = false;
            // 註冊包含手機號, 需檢查驗證碼
            if (!empty($input['mobile']) && !empty($input['mobile_token'])) {
                // 檢查手機號是否已超過允許綁定的次數
                $hasReachedEmailBindingLimit = $this->memberService->hasReachedMobileBindingLimit($input['mobile'], $agent);

                if ($hasReachedEmailBindingLimit) {
                    throw new ApiException(__('error_message.1090'));
                }

                // 如果是辦公室 IP 且 token 為特定值，則放行
                $localTest = false;
                $officeIp = config('custom.office.ip');
                $clientIp = Common::getIp();
                if ($clientIp == $officeIp && $input['mobile_token'] == '0806449') {
                    $localTest = true;
                }

                if (!$localTest) {
                    $validateToken = [REDACTED]
                        ->where('token', $input['mobile_token'])
                        ->where('status', 0)
                        ->where('expire_date', '>=', date('Y-m-d H:i:s'))
                        ->first();

                    if (!$validateToken) {
                        throw new ApiException(__('error_message.9992'));
                    }

                    if ($validateToken->info != $input['mobile']) {
                        throw new ApiException(__('error_message.9992'));
                    }
                }

                $mobileValidate = true;
            }

            if (!empty($input['email'])) {
                // 檢查Email是否已超過允許綁定的次射
                $hasReachedEmailBindingLimit = $this->memberService->hasReachedEmailBindingLimit($input['email'], $agent);

                if ($hasReachedEmailBindingLimit) {
                    throw new ApiException(__('error_message.1088'));
                }
            }

            // 檢查 username 是否與代理重複
            $checkAgent = Agent::where('username', $input['username'])->exists();
            if ($checkAgent) {
                throw new ApiException(__('error_message.1002'));
            }

            // 創建帳號
            $profile = [
                'parent' => $agent->id,
                'member_group_id' => $this->memberGroupService->defaultGroupIdForAgent($agent),
                'username' => $input['username'],
                'password' => Hash::make($input['password']),
                // 風控比對用(會員追蹤查同密碼帳號),不參與登入驗證
                'password_md5' => md5($input['password']),
                'email' => $input['email'] ?? null,
                'nickname' => $input['nickname'] ?? $this->registerService->getNickname(),
                'invitation_code' => $inviteCode,
                'device_id' => $input['device_id'] ?? null,
                'device_type' => $input['platform'] ?? null,
                'first_name' => $input['first_name'] ?? null,
                'last_name' => $input['last_name'] ?? null,
                'birthday' => $input['birthday'] ?? null,
                'mobile' => $input['mobile'] ?? null,
                'timezone_id' => $input['timezone_id'] ?? 0,
                'country_id' => $countryId,
                'zip_code' => $input['zip_code'] ?? null,
                'district' => $input['district'] ?? null,
                'city' => $input['city'] ?? null,
                'address' => $input['address'] ?? null,
                'status' => 1,
                'mobile_validate' => $mobileValidate,
                'admin' => 0,
                'register_ip' => ip2long(Common::getIp()),
                'register_domain' => $input['domain'] ?? null,
                'register_country_id' => $countryId,
                'type' => $memberType,
                'previous_day_type' => $memberType,
            ];

            $member = Member::create($profile);

            $this->registerService->createEventInviteJoin($member, $sponsor);

            // 邀請玩家獎勵
            if ($eventSummary) {
                // 寫入預派紀錄 TODO: 不應該耦合在此, 放在 SP_event_register 比較合適
                if ($prizeContent = PrizeContent::find($eventSummary->prize_content_id)) {
                    $prizeContent->increment('distribute');
                }
            }

            // 無限級代理
            if ($agent->agent_mode == 1) {
                $this->registerService->createMemberAgent($member, $agent, $sponsor);
            }

            // 如果有填寫EMAIL發送認證信
            // if (isset($input['email'])) {
            // 未實作
            // }

            // 手機綁定紀錄
            if ($mobileValidate) {
                MemberBindingLog::create([
                    'type' => MemberBindingLogTypeEnum::BINDING_PHONE->value,
                    'member_id' => $member->id,
                    'value' => $input['mobile'],
                    'ip' => Common::getIp(),
                    'validate_type' => 1,
                    'status' => 1,
                ]);
            }

            // 註冊成功後更新認證簡訊補上 member_id
            if (isset($validateToken)) {
                $validateToken->update([
                    'member_id' => $member->id,
                    'status' => 1, // 設為已使用
                ]);
            }

            DB::commit();

            // 註冊完成後，立即同步 CS DB 的資料
            $this->registerService->triggerCsSyncData($agent, $input['username']);
            $this->registerService->runRegisterEventStoredProcedures($member, $agent);

        } catch (Exception $e) {
            DB::rollBack();
            throw $e;
        }

        // 會員登入成功
        $member->load('memberSetting');
        $memberWallets = $this->walletService->getMemberWallets($member, true);
        $flowLimitApplicationStatus = $this->memberService->getFlowLimitApplicationStatus($member);
        $resource = new MemberDetailResource($member, $memberWallets, $flowLimitApplicationStatus);

        return ApiResponse::success($resource);
    }

    /**
     * v2 註冊帳號（3969）。
     *
     * 與 __invoke 差異：欄位驗證改走代理的 3970 註冊欄位設定（必填/字數動態），
     * 註冊限制改走 MemberRegisterLimitService（新表計數，不疊加舊 agent-setting 綁定上限）。
     * 建立會員核心與事件/CS/無限代理複用 RegisterService::createMember，與 __invoke 一致。
     *
     * 規則一律以 domain agent 為準（呈現與驗證一致，不隨邀請碼漂移）。
     */
    public function registerV2(RegisterV2Request $request)
    {
        $input = $request->validated();

        // 風控IP限制(4096)：來源IP有勾選「註冊」的啟用規則 → 擋註冊並累計重複次數
        $this->guardIpRestriction();

        $userData = $this->getUserContext();
        $domainAgent = $userData->agent;

        // ① 動態欄位驗證（依 domain agent 的 3970 註冊設定：必填 + 字數）
        $this->memberFieldSettingService->validateRegisterInput($domainAgent, $input);

        // 確認密碼一致性:僅在 confirm_password 欄位啟用時檢查(未啟用=前端不收此欄,送空值屬正常,跳過)
        if ($this->memberFieldSettingService->isRegisterFieldEnabled($domainAgent, MemberFieldKeyEnum::CONFIRM_PASSWORD->value)
            && ($input['confirm_password'] ?? '') !== ($input['password'] ?? '')
        ) {
            throw new ApiException(__('error_message.1021'), 1021);
        }

        // 驗證碼已併入手機/信箱欄位(欄位啟用=必驗):後端保險,有填值必須帶對應驗證碼,
        // 防直接打 API 略過驗證建號(前端已擋,此為後端保險驗證)
        if ($this->memberFieldSettingService->isRegisterFieldEnabled($domainAgent, MemberFieldKeyEnum::MOBILE->value)
            && ($input['mobile'] ?? '') !== '' && ($input['mobile_token'] ?? '') === ''
        ) {
            throw new ApiException(__('error_message.2053', ['field' => '手機驗證碼']), 2053);
        }
        if ($this->memberFieldSettingService->isRegisterFieldEnabled($domainAgent, MemberFieldKeyEnum::EMAIL->value)
            && ($input['email'] ?? '') !== '' && ($input['email_token'] ?? '') === ''
        ) {
            throw new ApiException(__('error_message.2053', ['field' => '郵件驗證碼']), 2053);
        }

        $inviteCode = $input['invitation_code'] ?? '';
        $inviteCodeType = $input['invitation_code_type'] ?? 0;
        if (empty($inviteCode)) {
            // 3969: 邀請碼(referral_code)是否必填一律以 3970 config 為準,不看舊個性化 9107。
            // config 要求必填才擋;否則留空用 domain agent code。詳見記憶 config-supersedes-customized。
            if ($this->memberFieldSettingService->isRegisterFieldRequired($domainAgent, MemberFieldKeyEnum::REFERRAL_CODE->value)) {
                throw new ApiException(__('error_message.2053', ['field' => '推薦碼']), 2053);
            }
            $inviteCode = $domainAgent->code;
        }

        [$agent, $sponsor, $eventSummary, $memberType] = $this->registerService->detectAgentAndSponsor($inviteCode, $inviteCodeType, $domainAgent);

        $this->registerService->validateBannedWords($input, $agent);

        $countryId = isset($input['country_code'])
            ? $this->registerService->getCountryIdByCode($input['country_code'])
            : 0;

        // 關閉模式：帳號由系統以前綴產生，忽略輸入的帳號（null＝非關閉模式）
        $usernamePrefix = $this->memberFieldSettingService->usernamePrefix($domainAgent);

        // ② 註冊限制（規則以 domain agent 為準）：查 DB 計數，達上限即擋
        //    以 Cache::lock 包住「檢查 + 建立」防併發超賣。關閉模式的一號一帳也在鎖內由綁定上限檢查擋下。
        $lockKey = "register_v2:{$domainAgent->organization_id}";
        $member = Cache::lock($lockKey, 10)->block(3, function () use ($input, $domainAgent, $agent, $sponsor, $eventSummary, $memberType, $inviteCode, $countryId, $usernamePrefix) {
            $this->assertRegisterV2Limits($input, $domainAgent);

            return $this->registerService->registerMemberV2(
                input: $input,
                agent: $agent,
                sponsor: $sponsor,
                eventSummary: $eventSummary,
                memberType: $memberType,
                inviteCode: $inviteCode,
                countryId: $countryId,
                usernamePrefix: $usernamePrefix,
            );
        });

        $member->load('memberSetting');
        $memberWallets = $this->walletService->getMemberWallets($member, true);
        $flowLimitApplicationStatus = $this->memberService->getFlowLimitApplicationStatus($member);

        return ApiResponse::success(new MemberDetailResource($member, $memberWallets, $flowLimitApplicationStatus));
    }

    /**
     * v2 註冊的兩類限制檢查（須在 Cache::lock 內、建號前呼叫）。
     *
     * - 註冊限制（type=6 agent_register_limits）：只交 name / ip_address，計同組織全部會員。
     * - 綁定上限（phone / email）：同組織＋同 binding_scope_id、只計已驗證會員。
     *   發碼階段雖已查過，但發碼到送出之間可能被他人用同號完成註冊、或隔日才送出，
     *   需在鎖內複查，否則可繞過綁定上限。
     *
     * phone / email 不交給註冊限制檢查。type=6 的 phone/email 列就是綁定上限檢查讀的上限值，
     * 後台沒勾選就不限制，見 MemberService::bindingLimitFor()；語意本來就是綁定上限的口徑。
     *
     * 若把 phone / email 也交給註冊限制檢查：兩者共用同一上限值時，註冊限制的計數（跨 binding_scope、
     * 含未驗證）是綁定上限的嚴格超集，會永遠先攔下（錯誤碼 2055），綁定上限檢查形同死碼；
     * 同組織下以 binding_scope 分站的品牌（togo／77win／WINT 的 organization_id 皆為 1）也會互相佔用
     * 手機名額（target/tickets#4309，現場案例 target/op_tickets#3092）。
     *
     * @throws ApiException
     */
    private function assertRegisterV2Limits(array $input, Agent $domainAgent): void
    {
        $exceeded = $this->memberRegisterLimitService->check($domainAgent, [
            'name' => $input['last_name'] ?? '',
            'ip_address' => Common::getIp(),
        ]);
        if ($exceeded !== null) {
            // 訊息用顯示名稱(如「真實姓名」),不把 field_key 原文(name/phone)丟給用戶
            throw new ApiException(
                __('error_message.2055', ['field' => MemberRegisterLimitFieldEnum::from($exceeded)->label()]),
                2055,
            );
        }

        if (!empty($input['mobile'])
            && $this->memberService->hasReachedMobileBindingLimit($input['mobile'], $domainAgent)
        ) {
            throw new ApiException(__('error_message.1090'), 1090);
        }

        if (!empty($input['email'])
            && $this->memberService->hasReachedEmailBindingLimit($input['email'], $domainAgent)
        ) {
            throw new ApiException(__('error_message.1088'), 1088);
        }
    }

    /**
     * 風控IP限制(4096)：註冊入口共用的阻擋檢查。
     *
     * 兩支註冊 API（register，以及 target/tickets#3969 的 register-v2）都要擋，行為與訊息一致。
     *
     * @throws ApiException
     */
    private function guardIpRestriction(): void
    {
        if ($this->ipRestrictionGuard->blockAttempt(Common::getIp(), IpRestrictionBlockItemEnum::REGISTER)) {
            throw new ApiException(
                IpRestrictionBlockItemEnum::REGISTER->message(),
                IpRestrictionBlockItemEnum::REGISTER->errorCode(),
            );
        }
    }
}
