<?php

declare(strict_types=1);

namespace App\Http\Requests\Frontend;

use App\Helpers\Traits\GetContextTrait;
use App\Http\Requests\AbstractRequest;
use App\Rules\Username;
use App\Services\MemberFieldSettingService;

/**
 * v2 註冊請求（target/tickets#3969）。
 *
 * 基礎格式驗證僅止於型別 / 基本格式；「是否必填、字數上下限」一律由代理的
 * 註冊欄位設定（target/tickets#3970，agent_member_field_settings）於 controller 動態判定，
 * 不在此寫死，以免與 config 規則衝突。
 *
 * 註冊帳號（username，錯誤訊息顯示為「玩家帳號」）的字元規則與第一版註冊 API register 相同
 * （target/tickets#4313）：只能英數、至少一個英文字母，
 * 純數字帳號一律擋下（避免與他人手機號撞號、手機登入撈錯人）。
 *
 * 網域代理的組別在關閉模式時，帳號由系統產生，前端帶來的帳號整個排除（不檢查、不進 validated），
 * 後續的禁用字檢查也就碰不到它。
 */
class RegisterV2Request extends AbstractRequest
{
    use GetContextTrait;

    public function rules(): array
    {
        $agent = $this->getUserContext()?->agent;
        $usernameAutoGenerated = $agent !== null
            && app(MemberFieldSettingService::class)->isUsernameAutoGenerated($agent);

        return [
            'username' => $usernameAutoGenerated ? ['exclude'] : ['nullable', 'string', new Username],
            'password' => ['nullable', 'string'],
            'confirm_password' => ['nullable', 'string'],   // 對齊 config field_key
            'last_name' => ['nullable', 'string'],   // 真實姓名
            'mobile' => ['nullable', 'string'],
            'mobile_token' => ['nullable', 'string'],   // 手機驗證碼
            'email' => ['nullable', 'string', 'email'],
            'email_token' => ['nullable', 'string'],   // 郵件驗證碼
            'birthday' => ['nullable', 'string', 'date_format:Y-m-d'],
            'referral_code' => ['nullable', 'string'],
            'invitation_code' => ['nullable', 'string'],
            'invitation_code_type' => ['nullable', 'integer'],
            'country_code' => ['nullable', 'string'],
            'device_id' => ['nullable', 'string'],
            'platform' => ['nullable', 'string'],
            'domain' => ['nullable', 'string'],
        ];
    }

    /** 錯誤訊息顯示「玩家帳號」而非「帳號」，與第一版註冊 API register（RegisterRequest）相同 */
    public function attributes(): array
    {
        return [
            'username' => __('validation.attributes.player_account'),
        ];
    }
}
