<?php

declare(strict_types=1);

namespace App\Http\Requests\Frontend;

use App\Helpers\Traits\GetContextTrait;
use App\Http\Requests\AbstractRequest;
use App\Services\MemberFieldSettingService;

class LoginRequest extends AbstractRequest
{
    use GetContextTrait;

    public function rules(): array
    {
        return [
            /**
             * 帳號
             *
             * @example test
             */
            'username' => 'required|string',
            /**
             * 密碼
             *
             * @example 123456
             */
            'password' => 'required|string',
            /**
             * 域名
             *
             * @example example.invalid
             */
            'domain' => 'required|string',
            'platform' => 'nullable|string',
            'device_id' => 'nullable|string',
            'app' => 'nullable|string',
            'do_2fa' => 'nullable|string',
            'secret' => 'nullable|string',
        ];
    }

    /**
     * 網域代理的組別在關閉模式時，會員只用手機號碼登入，帳號或密碼沒填改說「手機號碼或密碼不可為空」。
     */
    public function messages(): array
    {
        $agent = $this->getUserContext()?->agent;
        if ($agent === null || !app(MemberFieldSettingService::class)->isUsernameAutoGenerated($agent)) {
            return [];
        }

        return [
            'username.required' => __('error_message.9004_mobile'),
            'password.required' => __('error_message.9004_mobile'),
        ];
    }

    public function attributes(): array
    {
        return [
            'username' => __('validation.attributes.player_account'),
        ];
    }
}
