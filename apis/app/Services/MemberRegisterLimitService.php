<?php

declare(strict_types=1);

namespace App\Services;

use App\Enums\General\CacheTtl;
use App\Enums\MemberRegisterLimitFieldEnum;
use App\Models\Agent;
use App\Models\AgentRegisterLimit;
use App\Models\Member;
use Illuminate\Support\Facades\Cache;

/**
 * 註冊限制檢查（agent_register_limits，agent_groups type=6）。
 *
 * 3969：v2 註冊送出時，查 DB 計數判定「同一值可被重複註冊的次數」是否超限。
 * 演算法：正規化 → 自訂逐值優先（命中即覆蓋平台預設）→ 未命中走平台上限。
 * 計數含未驗證會員（寫入即佔名額）。併發防超賣由呼叫端以 Cache::lock 包住「檢查 + 建立」。
 *
 * 限制值一律不下發前端，純後端強制。與讀取/呈現規則職責分離（見 MemberFieldSettingService）。
 */
class MemberRegisterLimitService
{
    public function __construct(
        protected MemberFieldSettingService $fieldSettingService,
    ) {}

    /**
     * 檢查各限制欄位是否超限；未達上限回 null（通過），達上限回超限的 field_key。
     *
     * @param  array{email?:string, phone?:string, name?:string, ip_address?:string}  $values  傳入原始值
     */
    public function check(Agent $agent, array $values): ?string
    {
        $groupId = $this->fieldSettingService->resolveGroupId($agent);
        if ($groupId === null) {
            return null;
        }

        $limits = $this->getLimits($groupId);

        foreach ($limits as $limit) {
            $field = $limit['field_key'];

            // 已淘汰的 field_key（如殘留的 password 列）不參與判斷，避免呼叫端 enum::from 拋 ValueError
            if (MemberRegisterLimitFieldEnum::tryFrom($field) === null) {
                continue;
            }

            $raw = $values[$field] ?? null;
            if ($raw === null || $raw === '') {
                continue;
            }
            $value = $this->normalize($field, (string) $raw);

            if ($this->exceeds($agent, $field, $value, $limit)) {
                return $field;
            }
        }

        return null;
    }

    /**
     * 取單一欄位的「綁定/註冊上限」值（自訂逐值命中優先，未命中走平台上限）。
     * 供綁定類檢查取「上限值」用（計數口徑由呼叫端自理，與 check() 的含未驗證計數無關）。
     *
     * 回 null = 該欄位限制未啟用（後台「註冊/綁定限制」未勾選）= 不限制。
     * $value 供自訂逐值比對；傳空字串則略過自訂、只看平台上限。
     */
    public function bindingLimit(Agent $agent, MemberRegisterLimitFieldEnum $field, string $value = ''): ?int
    {
        // 關閉模式的手機號碼一律回 1（一號一帳），不管註冊/綁定限制設多少，資料庫裡的設定值不動。
        // 註冊、換綁手機、TG 補手機、送驗證碼前的預先檢查都經過這裡，一號一帳在這些入口一起生效
        if ($field === MemberRegisterLimitFieldEnum::PHONE && $this->fieldSettingService->isUsernameAutoGenerated($agent)) {
            return 1;
        }

        $groupId = $this->fieldSettingService->resolveGroupId($agent);
        if ($groupId === null) {
            return null;
        }

        foreach ($this->getLimits($groupId) as $limit) {
            if ($limit['field_key'] !== $field->value) {
                continue;
            }

            if ($value !== '' && $limit['custom_enabled'] === 1) {
                $normalized = $this->normalize($field->value, $value);
                foreach ($limit['values'] as $cv) {
                    if ($this->matchCustom($field->value, $normalized, $cv['value'])) {
                        return (int) $cv['max_limit'];
                    }
                }
            }

            if ($limit['platform_enabled'] === 1 && $limit['platform_max_limit'] !== null) {
                return $limit['platform_max_limit'];
            }

            return null;
        }

        return null;
    }

    /**
     * 單一欄位：自訂逐值優先，未命中走平台上限。
     *
     * @param  array{field_key:string, platform_enabled:int, platform_max_limit:int|null, custom_enabled:int, values:array<int,array{value:string,max_limit:int}>}  $limit
     */
    private function exceeds(Agent $agent, string $field, string $value, array $limit): bool
    {
        // ① 自訂逐值優先
        if ($limit['custom_enabled'] === 1) {
            foreach ($limit['values'] as $cv) {
                if ($this->matchCustom($field, $value, $cv['value'])) {
                    return $this->countMembers($agent, $field, $cv['value'], custom: true) >= $cv['max_limit'];
                }
            }
        }

        // ② 平台上限（自訂未命中才看）
        if ($limit['platform_enabled'] === 1 && $limit['platform_max_limit'] !== null) {
            return $this->countMembers($agent, $field, $value, custom: false) >= $limit['platform_max_limit'];
        }

        return false;
    }

    /**
     * 計數同 organization_id 下符合條件的會員。
     * custom=true 且為不含 @ 的 email 值時，計整個網域；否則精確比對完整值。
     */
    private function countMembers(Agent $agent, string $field, string $matchValue, bool $custom): int
    {
        $query = Member::query()->whereHas(
            'agent',
            fn ($q) => $q->where('organization_id', $agent->organization_id)
        );

        return match ($field) {
            MemberRegisterLimitFieldEnum::EMAIL->value => $custom && !str_contains($matchValue, '@')
                ? (clone $query)->where('email', 'like', '%@' . $matchValue)->count()
                : (clone $query)->where('email', $matchValue)->count(),
            MemberRegisterLimitFieldEnum::PHONE->value => (clone $query)->where('mobile', $matchValue)->count(),
            MemberRegisterLimitFieldEnum::NAME->value => (clone $query)->where('first_name', $matchValue)->count(),
            MemberRegisterLimitFieldEnum::IP_ADDRESS->value => (clone $query)->where('register_ip', ip2long($matchValue) ?: 0)->count(),
            default => 0,
        };
    }

    /**
     * 自訂逐值比對：email 含 @ → 完整精確；不含 @ → 網域精確相等（非 substring，避免 example.invalid 誤傷）。
     */
    private function matchCustom(string $field, string $incoming, string $configValue): bool
    {
        $configValue = $this->normalize($field, $configValue);

        if ($field === MemberRegisterLimitFieldEnum::EMAIL->value && !str_contains($configValue, '@')) {
            return substr((string) strrchr($incoming, '@'), 1) === $configValue;
        }

        return $incoming === $configValue;
    }

    private function normalize(string $field, string $value): string
    {
        $value = trim($value);

        return match ($field) {
            MemberRegisterLimitFieldEnum::EMAIL->value,
            MemberRegisterLimitFieldEnum::PHONE->value => mb_strtolower($value),
            default => $value,
        };
    }

    /**
     * 清掉某組別的註冊限制快取，存檔後呼叫，讓註冊馬上套用新設定。鍵要跟 getLimits() 的快取鍵一致。
     */
    public function forgetCache(int $groupId): void
    {
        Cache::forget("member_register_limit:{$groupId}");
    }

    /**
     * 取某組別啟用中的註冊限制（含自訂逐值），快取。
     *
     * @return array<int, array{field_key:string, platform_enabled:int, platform_max_limit:int|null, custom_enabled:int, values:array<int,array{value:string,max_limit:int}>}>
     */
    private function getLimits(int $groupId): array
    {
        return Cache::safeRemember(
            "member_register_limit:{$groupId}",
            CacheTtl::ONE_MINUTE->value,
            fn () => AgentRegisterLimit::query()
                ->with('values:id,register_limit_id,value,max_limit')
                ->where('agent_group_id', $groupId)
                ->where(fn ($q) => $q->where('platform_enabled', 1)->orWhere('custom_enabled', 1))
                ->get()
                ->map(fn (AgentRegisterLimit $row) => [
                    'field_key' => $row->field_key,
                    'platform_enabled' => (int) $row->platform_enabled,
                    'platform_max_limit' => $row->platform_max_limit === null ? null : (int) $row->platform_max_limit,
                    'custom_enabled' => (int) $row->custom_enabled,
                    'values' => $row->values
                        ->map(fn ($v) => ['value' => (string) $v->value, 'max_limit' => (int) $v->max_limit])
                        ->all(),
                ])
                ->all()
        );
    }
}
